const init = decodeMessage(initGolden);
assert(init.envelope.session === 0x0102030405060708n, "init session mismatch");
assert(init.envelope.sequence === 1n, "init sequence mismatch");
assert(init.packet.type === "init", "init kind mismatch");
assert(init.packet.surface.width === 1280, "init width mismatch");
assert(init.packet.surface.height === 720, "init height mismatch");
assert(init.packet.surface.scaleFactor === 1.5, "init scale mismatch");
assert(init.packet.backend === 0, "init backend mismatch");
assert(init.packet.colorSpace === 1, "init color-space mismatch");
assert(init.packet.alphaMode === 2, "init alpha mismatch");

const resources = decodeMessage(resourceGolden);
assert(resources.packet.type === "resource-batch", "resource kind mismatch");
assert(resources.packet.resourceEpoch === 7n, "resource epoch mismatch");
assert(resources.packet.updates.length === 1, "resource count mismatch");
assert(resources.packet.updates[0].handle.slot === 3, "resource slot mismatch");
assert(resources.packet.updates[0].handle.generation === 2, "generation mismatch");
assert(resources.packet.updates[0].contentId === 0x1122334455667788n, "content id mismatch");
assert(
  Array.from(resources.packet.updates[0].bytes).join(",") === "170,187,204",
  "resource bytes mismatch",
);

const frame = decodeMessage(frameGolden);
assert(frame.packet.type === "frame", "frame kind mismatch");
assert(frame.packet.frameId === 9n, "frame id mismatch");
assert(frame.packet.resourceEpoch === 7n, "frame resource epoch mismatch");
assert(frame.packet.semanticsEpoch === 5n, "frame semantics epoch mismatch");
assert(frame.packet.damage.length === 1, "frame damage count mismatch");
assert(frame.packet.damage[0].width === 100, "frame damage mismatch");
assert(
  Array.from(frame.packet.commands).join(",") === "222,173,190,239",
  "frame commands mismatch",
);

const state = new ProtocolSession();
state.accept(init);
state.accept(resources);
state.accept(frame);
assert(state.liveResourceCount() === 1, "resource was not made live");
assertProtocolError(() => state.accept(frame), "stale-sequence");

const badLength = new Uint8Array(initGolden.length + 1);
badLength.set(initGolden);
assertProtocolError(() => decodeMessage(badLength), "length-mismatch");

const badFlags = initGolden.slice();
badFlags[12] = 1;
assertProtocolError(() => decodeMessage(badFlags), "nonzero-reserved");

assertProtocolError(
  () => decodeMessage(initGolden, { ...DEFAULT_LIMITS, maxSurfaceDimension: 1000 }),
  "limit-exceeded",
);

